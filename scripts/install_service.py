"""Render/install a per-user unit and first-run config; never overwrite user config."""
import argparse
import os
from pathlib import Path

MARKER = '# Generated by crm4bridge scripts/install_service.py'


def path_value(value):
    value = str(value)
    if '\n' in value or '\r' in value or '\0' in value:
        raise ValueError('service paths cannot contain newlines or NUL')
    return value.replace('\\', '\\\\').replace('%', '%%')


def quote(value):
    return '"' + path_value(value).replace('"', '\\"') + '"'


def render_unit(repo, config):
    return f'''{MARKER}
[Unit]
Description=CR-M4 touchscreen Moonraker bridge
StartLimitIntervalSec=0

[Service]
Type=notify
NotifyAccess=main
WorkingDirectory={path_value(repo)}
ExecStart={quote(repo / '.venv/bin/python')} -m crm4bridge --config {quote(config)}
Environment=PYTHONUNBUFFERED=1
Restart=on-failure
RestartPreventExitStatus=2
RestartSec=10
TimeoutStartSec=30
TimeoutStopSec=15
KillSignal=SIGINT
UMask=0077

[Install]
WantedBy=default.target
'''


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--repo', type=Path, required=True)
    p.add_argument('--dry-run', action='store_true', help='print unit without writing files')
    a = p.parse_args()
    repo = a.repo.resolve()
    config_root = Path(os.environ.get('XDG_CONFIG_HOME', Path.home() / '.config'))
    config = config_root / 'crm4bridge/crm4bridge.cfg'
    unit = config_root / 'systemd/user/crm4bridge.service'
    content = render_unit(repo, config)
    if a.dry_run:
        print(content, end='')
        return
    if unit.exists() and not unit.read_text().startswith(MARKER):
        raise SystemExit(f'{unit} was not generated by this installer; preserve/reconcile it manually')
    os.umask(0o077)
    config.parent.mkdir(parents=True, exist_ok=True)
    if not config.exists():
        with config.open('x') as f:
            f.write('''[bridge]
moonraker = http://127.0.0.1:7125
screen = serial:/dev/serial0@115200
screen_startup_timeout = 5
dry_run = true
machine_page = true
state_file = ~/.local/state/crm4bridge/state.json
''')
    unit.parent.mkdir(parents=True, exist_ok=True)
    unit.write_text(content)
    (Path.home() / '.local/state/crm4bridge').mkdir(parents=True, exist_ok=True)
    print(f'Config preserved/created: {config}\nUser unit installed: {unit}')


if __name__ == '__main__':
    main()
