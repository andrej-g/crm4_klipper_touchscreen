#!/usr/bin/env bash
# Remove only this installer's user service. Retain config, state and clone/venv.
set -Eeuo pipefail
case "${1:-}" in
    -h|--help) echo 'Usage: bash scripts/uninstall.sh (retains config, state, clone and venv)'; exit 0 ;;
    '') ;;
    *) echo 'Unexpected argument' >&2; exit 2 ;;
esac
[[ $EUID != 0 ]] || { echo 'Run as your login user.' >&2; exit 2; }
UNIT="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user/crm4bridge.service"
if [[ -e $UNIT ]]; then
    IFS= read -r FIRST <"$UNIT"
    [[ $FIRST == '# Generated by crm4bridge scripts/install_service.py' ]] || {
        echo 'Unit is not owned by this installer; preserve/reconcile manually.' >&2; exit 1;
    }
    systemctl --user disable --now crm4bridge.service
    rm -- "$UNIT"
    systemctl --user daemon-reload
    systemctl --user reset-failed crm4bridge.service || true
fi
echo 'User service removed. Config, state, clone/venv and linger setting retained.'
